/**
 * Generates docs/EN16931-COVERAGE.md from packages/core/src/terms.ts. CI regenerates it and fails on a diff
 * (see test/coverage-doc.test.ts and .github/workflows/ci.yml).
 */
import { writeFileSync } from 'node:fs';
import { EN16931_TERMS } from '../packages/core/src/terms.js';

export function renderCoverage(): string {
  const groups = EN16931_TERMS.filter((t) => t.id.startsWith('BG-'));
  const bts = EN16931_TERMS.filter((t) => t.id.startsWith('BT-'));
  const row = (t: (typeof EN16931_TERMS)[number]) =>
    `| ${t.id} | ${t.name} | \`${t.path}\` | ${t.kind} | ${t.fixture ? `[${t.fixture}](../fixtures/${t.fixture})` : '(computed/derived)'} |`;
  return [
    '# EN 16931 coverage',
    '',
    '<!-- Generated by tools/generate-coverage.ts from packages/core/src/terms.ts. Do not hand-edit. -->',
    '',
    `Every business term (BT) and group (BG) of EN 16931-1 and where it lives in the \`Invoice\` model: **${bts.length} terms and ${groups.length} groups**.`,
    'Each input term is proven by a fixture that is written to CII and UBL, read back, and compared field by field',
    '(`test/model-roundtrip.test.ts`, `test/parse-roundtrip.test.ts`), then validated against the XSD and the CEN Schematron',
    '(`tools/validate.py`, `test/validate.test.ts`). `test/coverage-doc.test.ts` fails if this table drifts from the model.',
    '',
    'Known cardinality limits: BG-16 supports one payment-means type per invoice (further accounts of the same type are',
    'kept in `payment.additionalAccounts`); BT-81 values that differ between repeated BG-16 are not representable.',
    '',
    '## Business groups',
    '',
    '| ID | Name | Model path | Kind | Proven by |',
    '|---|---|---|---|---|',
    ...groups.map(row),
    '',
    '## Business terms',
    '',
    '| ID | Name | Model path | Kind | Proven by |',
    '|---|---|---|---|---|',
    ...bts.map(row),
    '',
  ].join('\n');
}

if (process.argv[1]?.endsWith('generate-coverage.ts')) {
  writeFileSync(new URL('../docs/EN16931-COVERAGE.md', import.meta.url), renderCoverage());
  console.log('wrote docs/EN16931-COVERAGE.md');
}
