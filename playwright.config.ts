import { defineConfig } from '@playwright/test';

/**
 * The end-to-end gate: a Playwright test that creates an invoice end to end
 * and asserts the downloaded PDF passes tools/validate.py. Runs against the
 * PRODUCTION build (`vite build` + `vite preview`), not the dev server —
 * that's what actually ships, and it's the only mode where the service
 * worker (and therefore the offline story) is real. This gate exists so
 * that path is checked by CI on every push, not just by hand.
 */
export default defineConfig({
  testDir: './e2e',
  // e2e/screenshots.spec.ts writes docs/screenshots; it is a generator, run only with SCREENSHOTS=1.
  testIgnore: process.env.SCREENSHOTS ? [] : ['**/screenshots.spec.ts'],
  timeout: 60_000,
  fullyParallel: false, // one worker: the local numbering counter is shared, global IndexedDB state
  retries: 0,
  reporter: [['list']],
  use: {
    baseURL: 'http://localhost:5183',
    trace: 'retain-on-failure',
  },
  webServer: [
    {
      command: 'npm run build --workspace=packages/ui && npm run preview --workspace=packages/ui -- --port 5183 --strictPort',
      url: 'http://localhost:5183',
      reuseExistingServer: !process.env.CI,
      timeout: 180_000,
    },
    {
      // The validator page, a separate deployable (e2e/validator.spec.ts, e2e/a11y.spec.ts, e2e/layout.spec.ts).
      command: 'npm run build --workspace=packages/validator-page && npm run preview --workspace=packages/validator-page -- --port 5184 --strictPort',
      url: 'http://localhost:5184',
      reuseExistingServer: !process.env.CI,
      timeout: 180_000,
    },
    {
      // The docs site: static pages generated by packages/docs-site.
      command: 'npm run docs:build && node tools/serve-static.mjs packages/docs-site/dist 5185',
      url: 'http://127.0.0.1:5185/index.html',
      reuseExistingServer: !process.env.CI,
      timeout: 180_000,
    },
  ],
});
